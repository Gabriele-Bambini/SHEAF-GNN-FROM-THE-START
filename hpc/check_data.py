from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
from typing import Iterable

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from tsgnn.data.allele import TP53_HOTSPOT_MUTATIONS
REQUIRED_EXACT = {
    "raw": [
        "raw/tcga/tcga_brca_tp53_mutations.csv",
        "raw/brca/wu2021_tp53_alleles.csv",
        "raw/brca/GSE158508/GSE158508_normalized_counts.txt",
        "raw/brca/GSE176078/GSE176078_Wu_etal_2021_BRCA_scRNASeq.tar.gz",
        "raw/brca/BIOKEY_E-MTAB-8107/E-MTAB-8107.sdrf.txt",
        "raw/crc/GSE178341_crc10x_full_c295v4_submit.h5",
        "raw/metabric/data_clinical_patient.txt",
        "raw/metabric/data_clinical_sample.txt",
        "raw/metabric/data_mutations.txt",
        "raw/metabric/data_mrna_illumina_microarray.txt",
    ],
    "processed": [
        # Generated by run_nature.py on first run — not required to pre-exist
        # "processed/brca_malignant_raw.h5ad",  # old pipeline only
        # "processed/brca_preprocessed.h5ad",   # old pipeline only
        # "processed/grn_artifacts.pt",          # old pipeline only
        # "processed/temporal_sequences.pt",     # old pipeline only
        "processed/multiprior_grn.parquet",
    ],
}
REQUIRED_ANY = {
    "external": [
        ["external/regnetwork/human_regulatory.txt", "external/regnetwork/human.source"],
        ["external/targetgenereg/p53_targets_benchmark.csv", "external/targetgenereg/p53_targets_benchmark.xlsx"],
        ["external/string/9606.protein.links.v12.0.txt", "external/string/9606.protein.links.v12.0.txt.gz"],
        ["external/string/9606.protein.aliases.v12.0.txt.gz"],
        ["external/jaspar/JASPAR2024_CORE_vertebrates.txt"],
    ]
}


def _load_required_alleles(config_path: Path | None) -> list[str]:
    if config_path and config_path.exists():
        cfg = yaml.safe_load(config_path.read_text(encoding="utf-8")) or {}
        alleles = cfg.get("data", {}).get("alleles")
        if alleles:
            return list(dict.fromkeys(["WT", *alleles]))
    return ["WT", *TP53_HOTSPOT_MUTATIONS.keys()]


def _embedding_status(data_dir: Path, alleles: Iterable[str]) -> dict:
    entries = {}
    for allele in alleles:
        path = data_dir / "external" / "esm2_embeddings" / f"{allele}.pt"
        entries[str(path.relative_to(data_dir))] = {
            "exists": path.exists(),
            "size": path.stat().st_size if path.exists() else 0,
        }
    return entries


def collect_status(data_dir: Path, config_path: Path | None = None) -> dict:
    status: dict[str, dict] = {}
    for group, paths in REQUIRED_EXACT.items():
        entries = {}
        for rel in paths:
            path = data_dir / rel
            entries[rel] = {
                "exists": path.exists(),
                "size": path.stat().st_size if path.exists() else 0,
            }
        status[group] = entries
    for group, groups in REQUIRED_ANY.items():
        entries = {}
        for candidates in groups:
            existing = [rel for rel in candidates if (data_dir / rel).exists()]
            label = " | ".join(candidates)
            size = 0
            if existing:
                size = sum((data_dir / rel).stat().st_size for rel in existing)
            entries[label] = {
                "exists": bool(existing),
                "size": size,
                "matched": existing,
            }
        status[group] = entries
    status["esm2_embeddings"] = _embedding_status(data_dir, _load_required_alleles(config_path))
    return status


def main() -> None:
    parser = argparse.ArgumentParser(description="Check required TS-GNN data files.")
    parser.add_argument(
        "--data-dir",
        default=os.environ.get("TSGNN_DATA_DIR", "data"),
        help="Base data directory on cluster",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print machine-readable JSON",
    )
    parser.add_argument(
        "--config",
        default=None,
        help="Optional config YAML used to derive required allele embeddings",
    )
    args = parser.parse_args()

    data_dir = Path(args.data_dir)
    config_path = Path(args.config) if args.config else None
    status = collect_status(data_dir, config_path=config_path)
    missing = [
        rel
        for group in status.values()
        for rel, meta in group.items()
        if not meta["exists"]
    ]

    if args.json:
        print(json.dumps({"data_dir": str(data_dir), "status": status, "missing": missing}, indent=2))
    else:
        print(f"TSGNN_DATA_DIR={data_dir}")
        for group, entries in status.items():
            ok = sum(1 for meta in entries.values() if meta["exists"])
            print(f"[{group}] {ok}/{len(entries)} present")
            for rel, meta in entries.items():
                tag = "OK" if meta["exists"] else "MISSING"
                print(f"  {tag:7} {rel}")

    if missing:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
